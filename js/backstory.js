// Генератор личности, внешности и истории персонажа (без ИИ, офлайн).
// История собирается из частей: происхождение (раса) → юность (предыстория) →
// путь к силе (класс) → то, что им движет (привязанность, идеал) → слабость → зацепка.
// Формы по полу пишутся как {мужская|женская}, имя — как [[имя]].

const pick = (a) => a[Math.floor(Math.random() * a.length)];
const shuffle = (a) => [...a].sort(() => Math.random() - 0.5);

export function genderOf(c) {
  if (c.gender === 'm' || c.gender === 'f') return c.gender;
  const first = String(c.name || '').split(' ')[0];
  return /[ая]$/i.test(first) || ['Мейв', 'Жаклин'].includes(first) ? 'f' : 'm';
}
export function g(text, gender, name = '') {
  return text
    .replace(/\{([^{}|]*)\|([^{}|]*)\}/g, (m0, m, f) => (gender === 'f' ? f : m))
    .replace(/\[\[имя\]\]/g, name);
}

