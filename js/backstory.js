export function generateAppearance(c, race) {
  const gd = genderOf(c);
  const r = RACE_LOOK[c.raceId];
  const parts = [
    `${pick(LOOKS.build)} ${race.size === 'Маленький' ? '(даже для своего роста)' : ''}`.trim(),
    r ? r : `волосы ${pick(LOOKS.hair)}`,
    `глаза ${pick(LOOKS.eyes)}`,
    `особая примета — ${pick(LOOKS.mark)}`,
  ];
  const s = parts.join('; ');
  return g(s.charAt(0).toUpperCase() + s.slice(1) + '.', gd);
}

export function generatePersonality(c) {
  const gd = genderOf(c);
  const b = pick(BONDS);
  c.traits = g(pick(TRAITS), gd);
  const idl = pick(IDEALS);
  c.ideals = idl.ideal;
  c.idealStory = idl.story;
  c.bonds = gd === 'f' && b.bondF ? b.bondF : b.bond;
  c.bondStory = gd === 'f' && b.storyF ? b.storyF : b.story;
  c.flaws = g(pick(FLAWS), gd);
}

export function generateBackstory(c, race, klass, bg) {
  const gd = genderOf(c);
  const name = String(c.name || 'Герой').split(' ')[0];
  const origin = pick(ORIGIN[c.raceId] || ORIGIN.human);
  const youth = pick(BG_STORY[bg.id] || BG_STORY.soldier);
  const path = pick(CLASS_STORY[klass.id] || CLASS_STORY.fighter);
  // привязанность: готовый сюжетный кусок или пересказ своими словами
  const bondKnown = BONDS.find((x) => x.bond === c.bonds || x.bondF === c.bonds);
  const bond = c.bondStory || (bondKnown ? (gd === 'f' && bondKnown.storyF ? bondKnown.storyF : bondKnown.story) : (c.bonds ? `Есть у {него|неё} и своя цель: ${c.bonds.replace(/\.$/, '').toLowerCase()}.` : ''));
  const idealKnown = IDEALS.find((x) => x.ideal === c.ideals);
  const ideal = c.idealStory && idealKnown && idealKnown.story === c.idealStory ? c.idealStory
    : idealKnown ? idealKnown.story
    : (c.ideals ? `Главное для {него|неё} — ${c.ideals.replace(/^[^:]+:\s*/, '').replace(/\.$/, '').replace(/^я /i, '').toLowerCase()}.` : '');
  const flaw = pick(FLAW_STORY);
  const hook = pick(HOOKS);
  const middle = shuffle([bond, ideal]).filter(Boolean);
  const text = [origin, youth, path, ...middle, flaw, hook].join(' ');
  return g(text, gd, name).replace(/\s+/g, ' ').trim();
}
