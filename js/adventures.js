export function generateDungeon(partySize = 4, avgLevel = 1) {
  const hi = Math.floor(Math.random() * HOOKS.length);
  const H = HOOKS[hi];
  const minions = MINIONS_BY_HOOK[hi];
  const rooms = 5 + Math.floor(Math.random() * 3);
  const scenes = {};
  const sid = (i) => 'room' + i;
  const groupSize = () => Math.max(1, Math.min(5, Math.round(partySize * (0.4 + Math.random() * 0.5) + (avgLevel - 1) * 0.5)));

  scenes.start = {
    title: H.place,
    text: `${H.hook} Вы стоите у входа: ${H.place}. Из темноты тянет холодом и опасностью. Факелы зажжены, оружие наготове.`,
    choices: [{ label: 'Войти внутрь', go: sid(1) }],
  };
  const types = ['combat', 'combat', 'trap', 'obstacle', 'npc', 'treasure', 'combat'];
  for (let i = 1; i <= rooms; i++) {
    const next = i === rooms ? 'boss' : sid(i + 1);
    let t = pick(types);
    if (i === 1) t = 'combat';
    if (i === Math.ceil(rooms / 2)) t = 'rest';
    const desc = pick(ROOM_DESC);
    if (t === 'combat') {
      const mk = pick(minions);
      const n = groupSize();
      const list = Array.from({ length: n }, (_, k) => (k === n - 1 && n > 2 ? pick(minions) : mk));
      scenes[sid(i)] = {
        title: `Зал ${i}`,
        text: `${desc} Внезапно из теней выходят враги: ${[...new Set(list.map((m) => MONSTERS[m].name.toLowerCase()))].join(' и ')}!`,
        choices: [
          { label: 'В бой!', go: sid(i) + 'f' },
          { label: 'Попытаться проскользнуть незаметно', check: { what: 'Скрытность', dc: 13, group: true }, ok: sid(i) + 's', fail: sid(i) + 'f' },
        ],
      };
      scenes[sid(i) + 'f'] = { title: `Бой: зал ${i}`, text: 'Враги бросаются в атаку!', combat: { monsters: list, win: sid(i) + 'w', lose: 'defeat' } };
      scenes[sid(i) + 's'] = { title: 'Незамеченными', text: 'Вы бесшумно проходите вдоль стены, пока враги ничего не подозревают.', effects: [{ type: 'xp', amount: 25 * list.length }], choices: [{ label: 'Идти дальше', go: next }] };
      scenes[sid(i) + 'w'] = { title: 'Победа в зале', text: `Враги повержены. Обыскав тела, вы находите немного монет.`, effects: [{ type: 'gold', amount: '2к6', who: 'actor' }], choices: [{ label: 'Идти дальше', go: next }] };
    } else if (t === 'trap') {
      const tr = pick(TRAPS);
      scenes[sid(i)] = {
        title: `Зал ${i}`,
        text: `${desc} Вы делаете шаг… ${tr.text}`,
        choices: [{ label: `Увернуться (${tr.save}, все)`, check: { what: tr.save, dc: 13, group: true }, ok: sid(i) + 'o', fail: sid(i) + 'x' }],
      };
      scenes[sid(i) + 'o'] = { title: 'Ловко!', text: 'Вы успеваете отскочить в последний миг. Ловушка лишь царапает камень.', effects: [{ type: 'xp', amount: 50 }], choices: [{ label: 'Идти дальше', go: next }] };
      scenes[sid(i) + 'x'] = { title: 'Ловушка сработала', text: 'Ловушка настигает вас. Боль пронзает тело, но вы поднимаетесь.', effects: [{ type: 'hp', amount: tr.dmg, who: 'all' }], choices: [{ label: 'Идти дальше', go: next }] };
    } else if (t === 'obstacle') {
      const o = pick(OBSTACLES);
      scenes[sid(i)] = { title: `Зал ${i}`, text: `${desc} ${o.text}`, choices: [{ label: `Преодолеть (${o.what}, СЛ ${o.dc})`, check: { what: o.what, dc: o.dc }, ok: sid(i) + 'o', fail: sid(i) + 'x' }] };
      scenes[sid(i) + 'o'] = { title: 'Препятствие пройдено', text: 'Вы справляетесь с преградой, и группа идёт дальше.', effects: [{ type: 'xp', amount: 50 }], choices: [{ label: 'Идти дальше', go: next }] };
      scenes[sid(i) + 'x'] = { title: 'Неудача', text: o.fail, effects: [{ type: 'hp', amount: '-1к6', who: 'actor' }], choices: [{ label: 'Идти дальше', go: next }] };
    } else if (t === 'npc') {
      const n = pick(NPCS);
      scenes[sid(i)] = { title: `Зал ${i}`, text: `${desc} ${n.text}`, choices: [{ label: `Поговорить (${n.what}, СЛ ${n.dc})`, check: { what: n.what, dc: n.dc }, ok: sid(i) + 'o', fail: sid(i) + 'x' }, { label: 'Пройти мимо', go: next }] };
      scenes[sid(i) + 'o'] = { title: 'Удачная встреча', text: n.ok, effects: [{ type: 'item', item: 'Зелье лечения', who: 'actor' }, { type: 'xp', amount: 50 }], choices: [{ label: 'Идти дальше', go: next }] };
      scenes[sid(i) + 'x'] = { title: 'Неудачная встреча', text: n.fail, effects: [{ type: 'hp', amount: '-1к4', who: 'actor' }], choices: [{ label: 'Идти дальше', go: next }] };
    } else if (t === 'treasure') {
      const tr = pick(TREASURES);
      scenes[sid(i)] = { title: `Зал ${i}`, text: `${desc} В углу стоит окованный железом сундук.`, choices: [{ label: 'Осмотреть сундук на ловушки', check: { what: 'Анализ', dc: 12 }, ok: sid(i) + 'o', fail: sid(i) + 'x' }, { label: 'Не трогать и идти дальше', go: next }] };
      scenes[sid(i) + 'o'] = { title: 'Сокровище', text: `Вы обезвреживаете иглу с ядом и открываете сундук. Внутри: ${tr} и горсть золота!`, effects: [{ type: 'item', item: tr, who: 'actor' }, { type: 'gold', amount: '3к10', who: 'actor' }], choices: [{ label: 'Идти дальше', go: next }] };
      scenes[sid(i) + 'x'] = { title: 'Ядовитая игла', text: `Игла с ядом впивается в палец! Но сокровище ваше: ${tr}.`, effects: [{ type: 'hp', amount: '-1к8', who: 'actor' }, { type: 'item', item: tr, who: 'actor' }], choices: [{ label: 'Идти дальше', go: next }] };
    } else {
      scenes[sid(i)] = { title: 'Безопасное место', text: `${desc} Здесь тихо и спокойно. Можно перевести дух.`, choices: [{ label: 'Короткий отдых', go: sid(i) + 'r' }, { label: 'Идти дальше без отдыха', go: next }] };
      scenes[sid(i) + 'r'] = { title: 'Отдых', text: 'Вы перевязываете раны и переводите дух. Кости хитов можно потратить в листе героя.', effects: [{ type: 'rest', long: false }], choices: [{ label: 'Идти дальше', go: next }] };
    }
  }
  const boss = BOSS_BY_HOOK[hi];
  const guards = Array.from({ length: Math.max(1, partySize - 2) }, () => pick(minions));
  scenes.boss = {
    title: 'Логово главаря',
    text: `Вы входите в последний зал. Здесь вас ждёт ${MONSTERS[boss].name} в окружении стражи. «Глупцы! Вы пришли умереть!» Голос главаря эхом отражается от стен.`,
    choices: [
      { label: 'В бой!', go: 'bossf' },
      { label: 'Запугать стражу', check: { what: 'Запугивание', dc: 14 }, ok: 'bossi', fail: 'bossf' },
    ],
  };
  scenes.bossf = { title: 'Последняя битва', text: 'Решающая схватка начинается!', combat: { monsters: [boss, ...guards], win: 'victory', lose: 'defeat' } };
  scenes.bossi = { title: 'Страх', text: 'Стража в ужасе разбегается, и главарь остаётся один!', effects: [{ type: 'xp', amount: 100 }], combat: { monsters: [boss], win: 'victory', lose: 'defeat' } };
  scenes.victory = {
    title: 'Победа!',
    text: `${MONSTERS[boss].name} повержен! Под троном вы находите сундук, полный золота. Подземелье «${H.place}» больше не угрожает окрестным землям, а ваши имена войдут в песни бардов.`,
    effects: [{ type: 'gold', amount: '50', who: 'all' }, { type: 'xp', amount: 200 }],
    end: 'win',
  };
  scenes.defeat = { ...ASH_MINE.scenes.defeat, text: 'Тьма смыкается над вами… Подземелье оказалось сильнее. Но это лишь один из путей. Создайте новое подземелье и попробуйте снова!' };
  return { id: 'random', title: H.place, desc: H.hook, start: 'start', scenes };
}
